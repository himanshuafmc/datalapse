// Build src/render/worldData.js: country outlines for the map race, already
// projected (Equal Earth) and packed small. Source: Natural Earth 1:110m via
// world-atlas (public domain / ISC).
//   node tools/build_world.mjs

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const topo = require('world-atlas/countries-110m.json');
const { feature } = require('topojson-client');
const iso = require('i18n-iso-countries');

const A1 = 1.340264;
const A2 = -0.081106;
const A3 = 0.000893;
const A4 = 0.003796;
const M = Math.sqrt(3) / 2;
function equalEarth(lon, lat) {
  const l = (lon * Math.PI) / 180;
  const p = (lat * Math.PI) / 180;
  const t = Math.asin(M * Math.sin(p));
  const t2 = t * t;
  const t6 = t2 * t2 * t2;
  const x = (2 * Math.sqrt(3) * l * Math.cos(t)) / (3 * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)));
  const y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  return [x, y];
}

const XMAX = equalEarth(180, 0)[0];
const W = 2000;
const S = W / (2 * XMAX);
// Leave out Antarctica (no data, lots of area): the map spans lat -58..84.
const YTOP = equalEarth(0, 84)[1];
const YBOT = equalEarth(0, -58)[1];
const H = Math.ceil((YTOP - YBOT) * S);

function zigzag(n) {
  return n >= 0 ? n * 2 : -n * 2 - 1;
}
function varint(bytes, n) {
  let v = zigzag(n);
  while (v >= 0x80) {
    bytes.push((v & 0x7f) | 0x80);
    v >>>= 7;
  }
  bytes.push(v);
}

// Rings that cross the 180° meridian (Fiji, Russia's far east) would draw
// a line across the whole map: unwrap them and cut them at 180°.
function clipHalf(ring, keepLeft) {
  const out = [];
  const inside = (p) => (keepLeft ? p[0] <= 180 : p[0] >= 180);
  for (let k = 0; k < ring.length; k++) {
    const a = ring[k];
    const b = ring[(k + 1) % ring.length];
    if (inside(a)) out.push(a);
    if (inside(a) !== inside(b)) {
      const f = (180 - a[0]) / (b[0] - a[0]);
      out.push([180, a[1] + f * (b[1] - a[1])]);
    }
  }
  return out;
}
function splitAntimeridian(ring) {
  let jumps = false;
  for (let k = 1; k < ring.length; k++) if (Math.abs(ring[k][0] - ring[k - 1][0]) > 180) jumps = true;
  if (!jumps) return [ring];
  const un = [ring[0].slice()];
  for (let k = 1; k < ring.length; k++) {
    let lon = ring[k][0];
    const prev = un[k - 1][0];
    while (lon - prev > 180) lon -= 360;
    while (lon - prev < -180) lon += 360;
    un.push([lon, ring[k][1]]);
  }
  // Shift so the ring sits around +180 (most of it east of 0)
  const mean = un.reduce((a, p) => a + p[0], 0) / un.length;
  const shifted = mean < 0 ? un.map(([x, y]) => [x + 360, y]) : un;
  const left = clipHalf(shifted, true);
  const right = clipHalf(shifted, false).map(([x, y]) => [x - 360, y]);
  return [left, right].filter((r) => r.length >= 3);
}

const fc = feature(topo, topo.objects.countries);
const shapes = {};
const names = {};
let points = 0;
for (const f of fc.features) {
  // Places without an ISO number: drawn with the country their data is
  // usually reported under.
  const ALIAS = { Kosovo: 'XK', Somaliland: 'SO', 'N. Cyprus': 'CY' };
  const a2 = (f.id ? iso.numericToAlpha2(f.id) : null) ?? ALIAS[f.properties.name] ?? null;
  const key = a2 ?? f.properties.name;
  if (key === 'AQ' || key === 'Antarctica') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const bytes = [];
  let rings = 0;
  for (const poly of polys) {
    for (const ring of poly.flatMap(splitAntimeridian)) {
      const pts = [];
      let px = null;
      let py = null;
      for (const [lon, lat] of ring) {
        const [x, y] = equalEarth(lon, Math.max(-58, lat));
        const qx = Math.round((x + XMAX) * S);
        const qy = Math.round((YTOP - y) * S);
        if (qx === px && qy === py) continue;
        pts.push([qx, qy]);
        px = qx;
        py = qy;
      }
      if (pts.length < 3) continue;
      rings++;
      varint(bytes, pts.length);
      let lx = 0;
      let ly = 0;
      for (const [x, y] of pts) {
        varint(bytes, x - lx);
        varint(bytes, y - ly);
        lx = x;
        ly = y;
      }
      points += pts.length;
    }
  }
  if (!rings) continue;
  const head = [];
  varint(head, rings);
  const b64 = Buffer.from(Uint8Array.from([...head, ...bytes])).toString('base64');
  shapes[key] = (shapes[key] ? `${shapes[key]} ` : '') + b64;
  if (!a2) names[key] = f.properties.name;
}

const out = `// Generated by tools/build_world.mjs from world-atlas (Natural Earth 1:110m,
// public domain). Do not edit. Equal Earth projection, ${W} x ${H} units,
// Antarctica left out. Each value is one or more space-separated base64
// blocks of zigzag varints: ringCount, then per ring pointCount and the
// x, y deltas.
export const WORLD_W = ${W};
export const WORLD_H = ${H};
export const WORLD_SHAPES = ${JSON.stringify(shapes)};
`;
writeFileSync(join(ROOT, 'src/render/worldData.js'), out);
console.log(`${Object.keys(shapes).length} shapes, ${points} points, ${(out.length / 1024).toFixed(0)} KB; unnamed: ${Object.keys(names).join(', ')}`);
