// Reference tables for the data doctor, built from the example data:
//  - population by country, 1950-2050 (Gapminder population v8, CC BY 4.0;
//    UN World Population Prospects projections after the latest year)
//  - US consumer prices, annual averages (BLS CPI-U from 1913, Shiller's
//    series before that), for inflation adjustment of US-dollar values
//   node tools/build_refdata.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findCountry } from '../src/data/countries.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(ROOT, 'reference/python/data');
const rows = (f) => readFileSync(join(DATA, f), 'utf8').trim().split(/\r?\n/).map((l) => l.split(','));

// population.csv: year, then one column per country (people)
const pop = rows('population.csv');
const header = pop[0];
const Y0 = 1950;
const Y1 = 2050;
const byYear = new Map(pop.slice(1).map((r) => [Number(r[0]), r]));
const countries = {};
const unmatched = [];
header.slice(1).forEach((name, j) => {
  const c = findCountry(name);
  if (!c) {
    unmatched.push(name);
    return;
  }
  const series = [];
  for (let y = Y0; y <= Y1; y++) {
    const v = Number(byYear.get(y)?.[j + 1]);
    series.push(Number.isFinite(v) && byYear.get(y)[j + 1] !== '' ? Math.round(v / 1000) : null);
  }
  countries[c.a2] = series;
});

// stocks_gold_cpi_monthly.csv: date, ..., us_cpi, ...
const m = rows('stocks_gold_cpi_monthly.csv');
const ci = m[0].indexOf('us_cpi');
const acc = new Map();
for (const r of m.slice(1)) {
  const y = Number(r[0].slice(0, 4));
  const v = Number(r[ci]);
  if (!Number.isFinite(v)) continue;
  const a = acc.get(y) ?? [0, 0];
  a[0] += v;
  a[1] += 1;
  acc.set(y, a);
}
const cpiYears = [...acc.keys()].filter((y) => acc.get(y)[1] >= 6).sort((a, b) => a - b);
const cpi = cpiYears.map((y) => Math.round((acc.get(y)[0] / acc.get(y)[1]) * 1000) / 1000);

const js = `// Generated by tools/build_refdata.mjs. Population: Gapminder population v8 (CC BY 4.0), in thousands.
// US CPI: annual averages of monthly CPI-U (BLS, public domain; Shiller before 1913).
export const POPULATION = { from: ${Y0}, to: ${Y1}, unit: 1000, countries: ${JSON.stringify(countries)} };
export const US_CPI = { from: ${cpiYears[0]}, to: ${cpiYears[cpiYears.length - 1]}, values: ${JSON.stringify(cpi)} };
`;
writeFileSync(join(ROOT, 'src/data/refData.js'), js);
console.log(`src/data/refData.js: ${Object.keys(countries).length} countries, CPI ${cpiYears[0]}-${cpiYears[cpiYears.length - 1]}, ${(js.length / 1024).toFixed(0)} KB`);
if (unmatched.length) console.log('unmatched:', unmatched.join(', '));
