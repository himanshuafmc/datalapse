// Rasterise the flag-icons SVGs (MIT) into one WebP sprite embedded in
// src/render/flagData.js. Run with Playwright's Chromium:
//   node tools/build_flags.mjs

import { chromium } from 'playwright';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'node_modules/flag-icons/flags/4x3');
const W = 72;
const H = 54;
const COLS = 16;
const files = readdirSync(DIR).filter((f) => f.endsWith('.svg') && /^[a-z]{2}\.svg$/.test(f)).sort();
const svgs = files.map((f) => [f.slice(0, 2).toUpperCase(), readFileSync(join(DIR, f), 'utf8')]);

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(pathToFileURL(join(ROOT, 'package.json')).href);
const result = await page.evaluate(async ({ svgs, W, H, COLS }) => {
  const rows = Math.ceil(svgs.length / COLS);
  const c = document.createElement('canvas');
  c.width = COLS * W;
  c.height = rows * H;
  const ctx = c.getContext('2d');
  const index = {};
  let k = 0;
  for (const [code, svg] of svgs) {
    const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
    const img = new Image();
    img.src = url;
    try {
      await img.decode();
    } catch {
      continue;
    }
    const x = (k % COLS) * W;
    const y = Math.floor(k / COLS) * H;
    ctx.drawImage(img, x, y, W, H);
    URL.revokeObjectURL(url);
    index[code] = k++;
  }
  return { data: c.toDataURL('image/webp', 0.9), index, rows };
}, { svgs, W, H, COLS });
await browser.close();

const js = `// Generated by tools/build_flags.mjs from flag-icons (MIT, github.com/lipis/flag-icons).
export const FLAG_SPRITE = { w: ${W}, h: ${H}, cols: ${COLS}, index: ${JSON.stringify(result.index)},
  data: '${result.data}' };
`;
writeFileSync(join(ROOT, 'src/render/flagData.js'), js);
console.log(`src/render/flagData.js: ${Object.keys(result.index).length} flags, ${(js.length / 1024).toFixed(0)} KB`);
