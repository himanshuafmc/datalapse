"""
Subset the video fonts to the characters stories use and embed them as
base64 WOFF2 in src/render/fontData.js.

    pip install fonttools brotli
    python3 tools/subset_fonts.py

Covered: Latin (incl. Latin-1 and Latin Extended-A, so most European
names), punctuation, currency signs incl. ₹, the minus sign and arrows;
Poppins also keeps Devanagari (Hindi, Marathi, Nepali) with its shaping rules.
Characters outside the subset still render: the browser falls back to a
system font for them.
"""
import base64
import io
import os

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "reference", "python", "fonts")
FACES = [("Poppins", 500, "Poppins-Medium.ttf"), ("Poppins", 700, "Poppins-Bold.ttf"),
         ("Roboto", 400, "Roboto-Regular.ttf"), ("Roboto", 500, "Roboto-Medium.ttf"),
         ("Roboto", 700, "Roboto-Bold.ttf")]
DEVANAGARI = [(0x0900, 0x097F), (0x200B, 0x200D), (0x25CC, 0x25CC), (0xA8E0, 0xA8FF), (0x1CD0, 0x1CFF)]
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x2010, 0x2027), (0x2030, 0x205E), (0x20A0, 0x20C0), (0x2190, 0x2199),
          (0x2212, 0x2212), (0x2122, 0x2122), (0x2026, 0x2026), (0x25B2, 0x25BC), (0x25CF, 0x25CF), (0x2713, 0x2713)]


def main():
    latin = [c for a, b in RANGES for c in range(a, b + 1)]
    deva = [c for a, b in DEVANAGARI for c in range(a, b + 1)]
    out = []
    total = 0
    for family, weight, fname in FACES:
        font = TTFont(os.path.join(FONTS, fname))
        opts = subset.Options()
        opts.flavor = "woff2"
        # Poppins also carries Devanagari, which needs all its shaping features.
        poppins = family == "Poppins"
        opts.layout_features = ["*"] if poppins else ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk", "tnum", "lnum"]
        unicodes = latin + deva if poppins else latin
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        opts.hinting = False
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=unicodes)
        sub.subset(font)
        buf = io.BytesIO()
        font.flavor = "woff2"
        font.save(buf)
        data = buf.getvalue()
        total += len(data)
        out.append((family, weight, base64.b64encode(data).decode("ascii")))
        print(f"  {fname}: {len(data) / 1024:.1f} KB")
    lines = ["// Generated by tools/subset_fonts.py. Poppins: SIL Open Font License 1.1. Roboto: Apache License 2.0.",
             "export const FONT_FACES = ["]
    for family, weight, b64 in out:
        lines.append(f"  {{ family: '{family}', weight: {weight}, data: '{b64}' }},")
    lines.append("];")
    path = os.path.join(ROOT, "src", "render", "fontData.js")
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  total {total / 1024:.0f} KB -> {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
